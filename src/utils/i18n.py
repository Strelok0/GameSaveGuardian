_current_lang = "en"


def set_language(lang: str) -> None:
    """Set global translation language ('en' or 'ar')."""
    global _current_lang
    if lang in TRANSLATIONS:
        _current_lang = lang


def get_language() -> str:
    """Get active language code."""
    return _current_lang


def is_rtl() -> bool:
    """Return True if active language is Right-to-Left (e.g. Arabic)."""
    return _current_lang == "ar"


def tr(key: str, **kwargs) -> str:
    """Lookup translation key in active language with fallback to English."""
    lang_dict = TRANSLATIONS.get(_current_lang, TRANSLATIONS["en"])
    text = lang_dict.get(key) or TRANSLATIONS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
